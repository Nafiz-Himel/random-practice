#include <bits/stdc++.h>
using namespace std;

int main()
{
    int day;
    cin >> day;

    switch(day)
    {
    case 1:
        cout << "n";
        break;
    case 2:
        cout << "nn";
        break;
    case 3:
        cout << "nnn";
        break;
    default:
        cout << "mm";
    }
    return 0;
}